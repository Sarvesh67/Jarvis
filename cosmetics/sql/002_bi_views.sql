-- BI serving layer for Metabase.
--
-- WHY THIS EXISTS
--   Metabase has no Neo4j driver, and the raw/staging tables in `public` are the wrong
--   shape for a BI tool: crosswalk is append-only with supersede chains, raw_company has
--   one row per (source, company) rather than per company, and trust lives in a third
--   table. Pointing Metabase at `public` produces plausible, wrong numbers.
--
--   This schema is the only surface Metabase is allowed to read. It is:
--     - resolved   — one row per entity, supersede chains already collapsed
--     - flat       — no arrays where a join table reads better
--     - documented — every view and column carries a COMMENT, which Metabase syncs into
--                    its own data dictionary, so the meaning travels with the data
--
-- WHAT IS DELIBERATELY ABSENT, AND WHY
--   `public.person`         — DPDP. Lab and firm contacts are named individuals with a
--                             recorded consent basis. They are not a BI dimension.
--   GST filing history      — hard rule 7. `trust_state.reasons` may record the fact of a
--                             filing check; the period is never exposed. Verify against
--                             it, rank with it, never display it.
--   `payload` / `evidence`  — raw JSON blobs that may carry either of the above.
--
--   Absence here is enforced, not just conventional: the `cosmetics_bi` role granted to
--   Metabase has USAGE on this schema only and no rights on `public`. Adding a view that
--   selects a person column would be the only way through, so don't.
--
-- Apply:  make bi-views       (idempotent — safe to re-run after every pipeline run)

BEGIN;

CREATE SCHEMA IF NOT EXISTS bi;
COMMENT ON SCHEMA bi IS
  'Read-only serving layer for Metabase. Resolved, flat, documented. Excludes person data and GST filing history by construction. Regenerated by sql/002_bi_views.sql.';

-- ---------------------------------------------------------------------------
-- Live crosswalk: the append-only table collapsed to current truth.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW bi.entity_source AS
SELECT
  c.entity_id,
  c.entity_type,
  c.source_id,
  c.source_key,
  c.method,
  c.score,
  c.decided_at
FROM public.crosswalk c
WHERE c.superseded_by IS NULL;

COMMENT ON VIEW bi.entity_source IS
  'Which sources contributed to each resolved entity, one row per (entity, source). Supersede chains are already collapsed — this is current truth, not history. Count DISTINCT entity_id here, never rows: a company seen by four sources has four rows.';
COMMENT ON COLUMN bi.entity_source.method IS
  'How the link was decided: exact identifier match, scored pair merge, or a human decision from the review queue.';
COMMENT ON COLUMN bi.entity_source.score IS
  'Pair score at merge time, 0-1. NULL for identifier-exact matches, which need no score. OPERATES requires >= 0.92 or a shared GSTIN/pincode.';

-- ---------------------------------------------------------------------------
-- Companies: one row per resolved entity.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW bi.company AS
WITH live AS (
  SELECT entity_id, source_id, source_key
  FROM public.crosswalk
  WHERE entity_type = 'company' AND superseded_by IS NULL
),
-- Lowest tier wins, then most recently retrieved. Tier 1 is the regulator.
best AS (
  SELECT DISTINCT ON (l.entity_id)
    l.entity_id,
    rc.legal_name,
    rc.norm_name,
    rc.constitution,
    rc.pincode,
    rc.district,
    rc.state,
    rc.cluster_id,
    rc.website,
    rc.tier AS spine_tier,
    rc.source_id AS spine_source
  FROM live l
  JOIN public.raw_company rc
    ON rc.source_id = l.source_id AND rc.source_key = l.source_key
  ORDER BY l.entity_id, rc.tier ASC, rc.retrieved_at DESC
),
agg AS (
  SELECT
    entity_id,
    count(*)                                   AS n_sources,
    min(source_id)                             AS first_source,
    array_agg(DISTINCT source_id ORDER BY source_id) AS sources
  FROM live
  GROUP BY entity_id
)
SELECT
  b.entity_id                       AS company_id,
  b.legal_name,
  b.norm_name,
  b.constitution,
  b.pincode,
  b.district,
  b.state,
  b.cluster_id,
  b.website,
  b.spine_tier,
  b.spine_source,
  a.n_sources,
  a.sources,
  t.trust_level,
  t.trust_rungs,
  (b.constitution = 'proprietorship') AS is_proprietorship,
  t.trust_grade,
  t.facets->'licence'->>'state' AS licence_facet,
  t.facets->'activity'->>'state' AS activity_facet,
  t.facets->'track'->>'state' AS track_facet
FROM best b
JOIN agg a USING (entity_id)
LEFT JOIN public.trust_state t ON t.entity_id = b.entity_id;

COMMENT ON VIEW bi.company IS
  'One row per resolved company. Spine fields are taken from the lowest-tier source that supplied them (regulator beats scraped), breaking ties on recency. A company with n_sources = 1 has been seen exactly once and corroborated by nothing.';
COMMENT ON COLUMN bi.company.trust_level IS
  'A MAXIMUM rung reached, not a score and not a category. Filtering trust_level = 2 silently drops everything above it. Filter on trust_rungs instead: 2 = ANY(trust_rungs).';
COMMENT ON COLUMN bi.company.trust_rungs IS
  'Every rung this entity actually satisfies. Deprecated 2026-10-31 with trust_level: use trust_grade and the facet columns.';
COMMENT ON COLUMN bi.company.trust_grade IS
  'Evidence grade (TRUST_PLAN §6.1): flagged, G0 listed, G1 registered, G2/G3 corroborated by 2 / 3+ independent publishers, G4 GST verified. Ordered and monotonic. Describes our evidence, not the firm, and never ranks suppliers.';
COMMENT ON COLUMN bi.company.spine_tier IS
  '1 regulator, 2 company-declared, 3 observed/scraped, 4 inferred. Tier 1 is the only tier that may answer a licence or compliance question.';
COMMENT ON COLUMN bi.company.n_sources IS
  'How many independent sources describe this company. The single most useful confidence proxy in the graph.';
COMMENT ON COLUMN bi.company.is_proprietorship IS
  'DPDP-relevant. A proprietorship GSTIN derives from an individual PAN and gets person-table handling upstream. Do not join this to anything identifying.';
COMMENT ON COLUMN bi.company.cluster_id IS
  'One of 17 clusters (4 of them wedge clusters). Assigned from pincode, never from district name alone — district names repeat across states.';

-- ---------------------------------------------------------------------------
-- Facilities and licences.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW bi.facility AS
WITH live AS (
  SELECT entity_id, source_id, source_key
  FROM public.crosswalk
  WHERE entity_type = 'facility' AND superseded_by IS NULL
)
SELECT DISTINCT ON (l.entity_id)
  l.entity_id        AS facility_id,
  rf.firm_name,
  rf.norm_name,
  rf.address_raw,
  rf.pincode,
  rf.district,
  rf.state,
  rf.licence_form,
  rf.licence_no,
  rf.licence_status,
  rf.granted_on,
  rf.expires_on,
  rf.is_loan_licence,
  rf.loan_premises_name,
  rf.tier,
  rf.source_id
FROM live l
JOIN public.raw_facility rf
  ON rf.source_id = l.source_id AND rf.source_key = l.source_key
ORDER BY l.entity_id, rf.tier ASC, rf.retrieved_at DESC;

COMMENT ON VIEW bi.facility IS
  'Resolved manufacturing sites and the licence held at each. Overwhelmingly drug-regime, not cosmetics — see catalog/sources/s01_cdsco.yaml. Of 911 rows, 3 are cosmetics-regime. Do not present a count from this view as a count of cosmetics facilities.';
COMMENT ON COLUMN bi.facility.licence_status IS
  'active | suspended | cancelled | unknown. Defaults to unknown — the register does not publish status, so unknown is the honest majority, not a data gap to be filled in.';
COMMENT ON COLUMN bi.facility.is_loan_licence IS
  'True when the licence names a second firm. Which of the two owns the plant is NOT knowable from the register — states fill the two name fields in opposite conventions. Never read a loan licence as "manufactures for".';

CREATE OR REPLACE VIEW bi.operates AS
SELECT
  o.company_id,
  o.facility_id,
  o.score,
  o.basis
FROM public.operates_edge o;

COMMENT ON VIEW bi.operates IS
  'Company -> Facility, the inferred join between the company spine and the licence register. Requires score >= 0.92 or a shared GSTIN/pincode; everything weaker goes to the review queue rather than into this view.';
COMMENT ON COLUMN bi.operates.basis IS
  'What carried the match: shared identifier, shared pincode plus name, or a reviewed human decision.';

-- ---------------------------------------------------------------------------
-- Ingredient supply claims.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW bi.ingredient_supply AS
SELECT
  s.entity_id   AS company_id,
  s.inci_name,
  s.matched_text,
  s.mode,
  s.tier,
  s.source_id,
  s.cosmetics_relevant
FROM public.raw_supplies s;

COMMENT ON VIEW bi.ingredient_supply IS
  'Tier 3. A company page mentioned an ingredient enough times, alongside enough others, to believe it sells it. A lead, not an inventory. Ambiguous INCI names that are also ordinary English (MILK, SAND, HONEY, TALC) are excluded rather than guessed at, and a page must yield >= 3 distinct ingredients before any is believed.';

-- ---------------------------------------------------------------------------
-- Pipeline health — the views that tell you whether to trust the others.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW bi.source_coverage AS
SELECT
  rc.source_id,
  min(rc.tier)                                   AS tier,
  count(*)                                       AS raw_rows,
  count(DISTINCT x.entity_id)                    AS resolved_entities,
  round(100.0 * count(DISTINCT x.entity_id) / NULLIF(count(*), 0), 1) AS resolve_pct,
  max(rc.retrieved_at)                           AS last_retrieved
FROM public.raw_company rc
LEFT JOIN public.crosswalk x
  ON x.source_id = rc.source_id
 AND x.source_key = rc.source_key
 AND x.superseded_by IS NULL
GROUP BY rc.source_id;

COMMENT ON VIEW bi.source_coverage IS
  'Per-source contribution to the company spine. resolve_pct below 100 is normal and usually correct — it means rows merged into an entity another source already supplied. A number far below 100 on a tier-1 source is worth investigating; on a directory source it is the point.';

CREATE OR REPLACE VIEW bi.source_freshness AS
SELECT
  f.source_id,
  count(*)                AS payloads,
  min(f.fetched_at)::date AS first_fetch,
  max(f.fetched_at)::date AS last_fetch,
  (CURRENT_DATE - max(f.fetched_at)::date) AS days_since_fetch,
  count(*) FILTER (WHERE f.http_status >= 400) AS failed_fetches
FROM public.fetch_manifest f
GROUP BY f.source_id;

COMMENT ON VIEW bi.source_freshness IS
  'When each source was last landed. raw/ is content-addressed and append-only, so a re-fetch of unchanged bytes does not appear here — a stale last_fetch means not re-fetched, not unchanged.';

CREATE OR REPLACE VIEW bi.trust_distribution AS
SELECT
  t.trust_level,
  count(*) AS entities,
  round(100.0 * count(*) / SUM(count(*)) OVER (), 1) AS pct
FROM public.trust_state t
GROUP BY t.trust_level;

CREATE OR REPLACE VIEW bi.trust_grade_distribution AS
SELECT
  t.trust_grade,
  count(*) AS entities,
  round(100.0 * count(*) / SUM(count(*)) OVER (), 1) AS pct
FROM public.trust_state t
GROUP BY t.trust_grade;

COMMENT ON VIEW bi.trust_grade_distribution IS
  'Entities per evidence grade (TRUST_PLAN §6.1). Since 2026-10-31 this, not trust_distribution, is what the card shows. 96% sit at G1: 99.7% of firms appear in exactly one publisher, so most cannot yet be told apart.';

COMMENT ON VIEW bi.trust_distribution IS
  'How many entities reached each trust rung, as a MAXIMUM. Most sit at L1: the Udyam long tail, registered and real but corroborated by nothing else. L0 is the remainder with no identifier or registry membership at all.';

CREATE OR REPLACE VIEW bi.review_queue_open AS
SELECT
  r.id,
  r.entity_type,
  r.left_key,
  r.right_key,
  r.score,
  r.status,
  r.decided_at
FROM public.review_queue r
WHERE r.status = 'pending';

COMMENT ON VIEW bi.review_queue_open IS
  'Resolution decisions a human has not made yet, highest-ambiguity first when sorted by score descending. This is a staffed workflow, not an exception hopper — norm_name + pincode is the primary resolution path for the MSME long tail. Work it with `python -m pipeline.review`.';

COMMIT;
